CREATE TABLE EVAL_SMALL (ID NUMBER PRIMARY KEY, AMOUNT NUMBER NOT NULL, NOTE VARCHAR2(100), CREATED_AT TIMESTAMP);
ALTER TABLE EVAL_SMALL ADD (STATUS VARCHAR2(20));
INSERT INTO EVAL_SMALL (ID, AMOUNT, NOTE, STATUS) VALUES (1, 100, 'initial', 'NEW');
