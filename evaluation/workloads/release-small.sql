CREATE OR REPLACE PROCEDURE EVAL_ADD(P_ID NUMBER) AS
BEGIN
  UPDATE EVAL_SMALL SET AMOUNT = AMOUNT + 1 WHERE ID = P_ID;
END;
/
CREATE OR REPLACE PACKAGE EVAL_PKG AS
  FUNCTION AMOUNT_OF(P_ID NUMBER) RETURN NUMBER;
END EVAL_PKG;
/
CREATE OR REPLACE PACKAGE BODY EVAL_PKG AS
  FUNCTION AMOUNT_OF(P_ID NUMBER) RETURN NUMBER AS V_AMOUNT NUMBER;
  BEGIN
    SELECT AMOUNT INTO V_AMOUNT FROM EVAL_SMALL WHERE ID = P_ID;
    RETURN V_AMOUNT;
  END;
BEGIN
  NULL;
END EVAL_PKG;
/
CREATE TABLE EVAL_EVENT (ID NUMBER, OLD_AMOUNT NUMBER, NEW_AMOUNT NUMBER);
CREATE OR REPLACE TRIGGER EVAL_TRG AFTER UPDATE OF AMOUNT ON EVAL_SMALL FOR EACH ROW
BEGIN
  INSERT INTO EVAL_EVENT VALUES (:NEW.ID, :OLD.AMOUNT, :NEW.AMOUNT);
END;
