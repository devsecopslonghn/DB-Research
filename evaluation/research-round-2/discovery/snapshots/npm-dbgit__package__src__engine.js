'use strict';
const os = require('os');
const { connect } = require('./db');
const { introspect } = require('./introspect');
const { diffSnapshots } = require('./diff');
const { generateStatements } = require('./sqlgen');
const { readLedger, recordDeploy, currentCommit } = require('./ledger');
const { parseType, normalizeColumn } = require('./types');
const merge = require('./merge');
const target = require('./target');
const store = require('./store');

async function withConnection(env, fn) {
  const conn = await connect(env);
  try {
    return await fn(conn);
  } finally {
    await conn.close().catch(() => {});
  }
}

async function captureSnapshot(env) {
  return withConnection(env, (conn) => introspect(conn, env.schema));
}

/** Creates schema/ and the first commit from an existing database. */
async function baseline(root, env, options = {}) {
  if (store.loadCommits(root).length > 0 && !options.force) {
    throw new Error('A baseline already exists. Use --force to replace it.');
  }
  const snapshot = await captureSnapshot(env);
  target.write(root, snapshot);

  const timestamp = store.stampNow();
  const snapshotFile = store.saveSnapshot(root, snapshot, `snap-0001-${timestamp}`);
  const migration = store.migrationFileName(timestamp, 'baseline');
  store.writeMigration(
    root,
    migration,
    [
      '-- baseline',
      `-- Captured from environment "${env.name}", schema ${snapshot.schema}.`,
      '--',
      '-- Intentionally empty: the baseline records the schema as it already',
      '-- exists rather than recreating it. Deploying to an environment that is',
      '-- already at this state produces no statements.',
      '',
    ].join('\n')
  );

  const commit = {
    id: '0001',
    message: 'baseline',
    createdAt: new Date().toISOString(),
    author: options.author || os.userInfo().username,
    schema: snapshot.schema,
    capturedFrom: env.name,
    snapshot: snapshotFile,
    migration,
    checksum: store.shortHash('baseline'),
    baseline: true,
    changeCount: 0,
    changes: [],
  };
  store.saveCommits(root, [commit]);
  return { commit, snapshot };
}

/** What has changed in the target schema since the last commit. */
function getStatus(root) {
  const desired = target.read(root);
  const base = store.headSnapshot(root);
  const head = store.headCommit(root);
  const changes = diffSnapshots(base, desired);
  return { desired, base, head, changes };
}

function buildMigrationSql(changes, options, meta) {
  const statements = generateStatements(changes, options);
  const header = [
    `-- ${meta.message}`,
    `-- commit ${meta.commitId}  |  ${meta.createdAt}  |  ${meta.author}`,
    `-- generated by dbgit for schema ${meta.schema}`,
    `-- ${changes.length} change(s)`,
    '',
  ];
  const body = statements.map((statement) =>
    statement.skipped ? statement.sql + '\n' : `-- ${statement.change.summary}\n${statement.sql}${statement.terminator}\n`
  );
  return { sql: header.concat(body).join('\n'), statements };
}

function commit(root, message, options = {}) {
  const { desired, changes } = getStatus(root);
  if (changes.length === 0) throw new Error('Nothing to commit — the target schema matches the last commit.');

  const commits = store.loadCommits(root);
  const commitId = store.nextCommitId(commits);
  const createdAt = new Date().toISOString();
  const author = options.author || os.userInfo().username;
  const timestamp = store.stampNow();

  const { sql, statements } = buildMigrationSql(changes, { allowDestructive: options.allowDestructive === true }, {
    commitId,
    message,
    createdAt,
    author,
    schema: desired.schema,
  });

  const fileName = store.migrationFileName(timestamp, message);
  store.writeMigration(root, fileName, sql);
  const snapshotFile = store.saveSnapshot(root, desired, `snap-${commitId}-${timestamp}`);

  const record = {
    id: commitId,
    message,
    createdAt,
    author,
    schema: desired.schema,
    snapshot: snapshotFile,
    migration: fileName,
    checksum: store.shortHash(sql),
    changeCount: changes.length,
    skippedCount: statements.filter((s) => s.skipped).length,
    changes: changes.map((change) => ({
      kind: change.kind,
      object: change.object,
      summary: change.summary,
      destructive: change.destructive,
    })),
  };
  commits.push(record);
  store.saveCommits(root, commits);

  return { commit: record, sql, migrationFile: fileName, skipped: statements.filter((s) => s.skipped) };
}

/**
 * The common ancestor for a three-way merge against one environment: the
 * schema as it stood at the commit this environment was last deployed to.
 *
 * Using the repository head instead would be wrong — everything committed but
 * not yet deployed would look like the environment had drifted, when in fact
 * the environment simply has not caught up yet.
 */
function baseFor(root, history) {
  const commits = store.loadCommits(root);
  const deployed = currentCommit(history);
  const match = commits.find((commit) => commit.id === deployed);
  const fallback = commits[0];
  const chosen = match || fallback;
  if (!chosen) return store.emptySnapshot();
  return store.loadSnapshot(root, chosen.snapshot) || store.emptySnapshot();
}

/**
 * Works out what deploying to an environment would do.
 *
 * The SQL is computed against the environment's actual state rather than
 * replayed from migration files, so an environment that is already partly
 * up to date only receives the statements it still needs.
 */
async function getDeployPlan(root, env, options = {}) {
  const desired = target.read(root);
  const decisions = options.decisions || {};

  return withConnection(env, async (conn) => {
    const live = await introspect(conn, env.schema);
    const history = await readLedger(conn);
    const base = baseFor(root, history);
    const analysis = merge.analyze({ base, target: desired, env: live, envName: env.name });
    const resolution = merge.resolve({ target: desired, env: live, conflicts: analysis.conflicts, decisions });

    const changes = diffSnapshots(live, resolution.forDeploy);
    const { sql, statements } = buildMigrationSql(
      changes,
      { allowDestructive: options.allowDestructive === true },
      {
        commitId: (store.headCommit(root) || {}).id || '(none)',
        message: `deploy to ${env.name}`,
        createdAt: new Date().toISOString(),
        author: options.author || os.userInfo().username,
        schema: env.schema,
      }
    );

    return {
      env: env.name,
      schema: env.schema,
      forward: analysis.forward,
      conflicts: analysis.conflicts,
      unresolved: resolution.unresolved,
      changes,
      statements: statements.map((s) => ({ sql: s.sql, skipped: s.skipped, summary: s.change && s.change.summary })),
      sql,
      history,
      currentCommit: currentCommit(history),
      headCommit: store.headCommit(root),
    };
  });
}

async function deploy(root, env, options = {}) {
  const desired = target.read(root);
  const decisions = options.decisions || {};
  const author = options.author || os.userInfo().username;
  const head = store.headCommit(root);

  return withConnection(env, async (conn) => {
    const live = await introspect(conn, env.schema);
    const base = baseFor(root, await readLedger(conn));
    const analysis = merge.analyze({ base, target: desired, env: live, envName: env.name });
    const resolution = merge.resolve({ target: desired, env: live, conflicts: analysis.conflicts, decisions });

    const changes = diffSnapshots(live, resolution.forDeploy);
    const generated = generateStatements(changes, { allowDestructive: options.allowDestructive === true });
    const runnable = generated.filter((item) => !item.skipped);

    if (options.dryRun) {
      return {
        env: env.name,
        dryRun: true,
        conflicts: analysis.conflicts,
        results: runnable.map((item) => ({ sql: item.sql, summary: item.change.summary, status: 'planned' })),
        skipped: generated.filter((item) => item.skipped).map((item) => item.change.summary),
      };
    }

    const results = [];
    const startedAt = Date.now();
    for (const item of runnable) {
      try {
        await conn.execute(item.sql);
        results.push({ sql: item.sql, summary: item.change.summary, status: 'ok' });
      } catch (error) {
        // Oracle commits DDL implicitly, so statements that already ran stay
        // applied. Stopping here keeps the failure from cascading, and the next
        // deploy recomputes from the environment's real state.
        results.push({ sql: item.sql, summary: item.change.summary, status: 'failed', error: error.message });
        return {
          env: env.name,
          dryRun: false,
          failed: true,
          conflicts: analysis.conflicts,
          results,
          skipped: generated.filter((i) => i.skipped).map((i) => i.change.summary),
        };
      }
    }

    if (head) {
      await recordDeploy(conn, {
        commitId: head.id,
        message: head.message,
        checksum: head.checksum,
        statementCount: results.length,
        appliedBy: author,
        durationMs: Date.now() - startedAt,
      });
    }

    // Conflicts resolved as take_env are now part of the intended design, so
    // they are written back into schema/ where they will be committed.
    if (Object.values(decisions).includes('take_env')) {
      target.write(root, resolution.forTarget);
    }

    return {
      env: env.name,
      dryRun: false,
      failed: false,
      conflicts: analysis.conflicts,
      adopted: Object.entries(decisions).filter(([, d]) => d === 'take_env').map(([locator]) => locator),
      results,
      skipped: generated.filter((item) => item.skipped).map((item) => item.change.summary),
    };
  });
}

/**
 * Brings changes made directly in a database back into the target schema —
 * the recovery path for an ALTER typed straight into SQL*Plus.
 */
async function pull(root, env, options = {}) {
  const desired = target.read(root);
  const decisions = options.decisions || {};

  return withConnection(env, async (conn) => {
    const live = await introspect(conn, env.schema);
    const base = baseFor(root, await readLedger(conn));
    const analysis = merge.analyze({ base, target: desired, env: live, envName: env.name });

    // Everything the environment has that the target does not is a candidate.
    const candidates = analysis.conflicts;
    if (options.plan) return { env: env.name, candidates };

    const effective = {};
    for (const conflict of candidates) {
      effective[conflict.locator] = decisions[conflict.locator] || (options.all ? 'take_env' : 'skip');
    }
    const resolution = merge.resolve({ target: desired, env: live, conflicts: candidates, decisions: effective });
    target.write(root, resolution.forTarget);

    const adopted = Object.entries(effective).filter(([, d]) => d === 'take_env').map(([locator]) => locator);
    return { env: env.name, candidates, adopted };
  });
}

const IDENTIFIER = /^[A-Za-z][A-Za-z0-9_$#]{0,29}$/;

function checkIdentifier(value, label) {
  if (!IDENTIFIER.test(String(value || ''))) {
    throw new Error(`Invalid ${label}: "${value}". Use letters, digits and underscores, up to 30 characters.`);
  }
  return String(value).toUpperCase();
}

/**
 * Applies a structured edit to the target schema files.
 *
 * Nothing here touches a database — the change becomes real only when it is
 * deployed to an environment.
 */
function editTarget(root, intent) {
  const desired = target.read(root);
  const op = intent.op;
  const tables = desired.tables;

  const requireTable = (name) => {
    const key = checkIdentifier(name, 'table name');
    if (!tables[key]) throw new Error(`Table ${key} is not in the target schema.`);
    return key;
  };

  switch (op) {
    case 'createTable': {
      const name = checkIdentifier(intent.table, 'table name');
      if (tables[name]) throw new Error(`Table ${name} already exists in the target schema.`);
      const table = { columns: {}, primaryKey: null, constraints: {}, indexes: {} };
      let position = 0;
      for (const column of intent.columns || []) {
        const columnName = checkIdentifier(column.name, 'column name');
        position += 1;
        table.columns[columnName] = buildColumn(column, position);
      }
      if (position === 0) throw new Error('A new table needs at least one column.');
      const pk = (intent.primaryKey || []).map((c) => checkIdentifier(c, 'primary key column'));
      if (pk.length) {
        const pkName = `PK_${name}`.slice(0, 30);
        table.primaryKey = { name: pkName, columns: pk };
        table.constraints[pkName] = { type: 'P', columns: pk, enabled: true };
        for (const column of pk) if (table.columns[column]) table.columns[column].nullable = false;
      }
      tables[name] = table;
      break;
    }
    case 'dropTable': {
      const name = requireTable(intent.table);
      delete tables[name];
      break;
    }
    case 'renameTable': {
      const name = requireTable(intent.table);
      const newName = checkIdentifier(intent.newName, 'new table name');
      if (tables[newName]) throw new Error(`Table ${newName} already exists.`);
      tables[newName] = tables[name];
      delete tables[name];
      break;
    }
    case 'addColumn': {
      const name = requireTable(intent.table);
      const columnName = checkIdentifier(intent.name, 'column name');
      if (tables[name].columns[columnName]) throw new Error(`Column ${name}.${columnName} already exists.`);
      const position = Object.keys(tables[name].columns).length + 1;
      tables[name].columns[columnName] = buildColumn(intent, position);
      break;
    }
    case 'modifyColumn': {
      const name = requireTable(intent.table);
      const columnName = checkIdentifier(intent.name, 'column name');
      const existing = tables[name].columns[columnName];
      if (!existing) throw new Error(`Column ${name}.${columnName} is not in the target schema.`);
      tables[name].columns[columnName] = buildColumn(intent, existing.position);
      break;
    }
    case 'renameColumn': {
      const name = requireTable(intent.table);
      const columnName = checkIdentifier(intent.name, 'column name');
      const newName = checkIdentifier(intent.newName, 'new column name');
      const columns = tables[name].columns;
      if (!columns[columnName]) throw new Error(`Column ${name}.${columnName} is not in the target schema.`);
      if (columns[newName]) throw new Error(`Column ${name}.${newName} already exists.`);
      // Rebuilt in place so the column keeps its position in the file.
      tables[name].columns = Object.fromEntries(
        Object.entries(columns).map(([key, value]) => (key === columnName ? [newName, value] : [key, value]))
      );
      break;
    }
    case 'dropColumn': {
      const name = requireTable(intent.table);
      const columnName = checkIdentifier(intent.name, 'column name');
      if (!tables[name].columns[columnName]) throw new Error(`Column ${name}.${columnName} is not in the target schema.`);
      delete tables[name].columns[columnName];
      break;
    }
    case 'addIndex': {
      const name = requireTable(intent.table);
      const indexName = checkIdentifier(intent.name, 'index name');
      const columns = (intent.columns || []).map((c) => checkIdentifier(c, 'index column'));
      if (columns.length === 0) throw new Error('An index needs at least one column.');
      for (const column of columns) {
        if (!tables[name].columns[column]) throw new Error(`Column ${name}.${column} is not in the target schema.`);
      }
      tables[name].indexes[indexName] = { unique: intent.unique === true, indexType: 'NORMAL', columns };
      break;
    }
    case 'dropIndex': {
      const name = requireTable(intent.table);
      const indexName = checkIdentifier(intent.name, 'index name');
      if (!tables[name].indexes[indexName]) throw new Error(`Index ${indexName} is not on ${name}.`);
      delete tables[name].indexes[indexName];
      break;
    }
    case 'setSource': {
      const key = String(intent.key || '');
      if (!desired.sources[key] && !intent.create) throw new Error(`Program unit ${key} is not in the target schema.`);
      const [type, name] = key.split(':');
      desired.sources[key] = { type, name, text: String(intent.text || '').trimEnd(), status: 'VALID' };
      break;
    }
    case 'setView': {
      const name = checkIdentifier(intent.name, 'view name');
      desired.views[name] = { text: String(intent.text || '').trimEnd() };
      break;
    }
    default:
      throw new Error(`Unknown edit operation "${op}".`);
  }

  target.write(root, desired);
  return desired;
}

function buildColumn(spec, position) {
  const parsed = parseType(spec.type || spec.dataType);
  return normalizeColumn({
    ...parsed,
    nullable: spec.notNull !== true,
    default: spec.default === undefined || spec.default === null || String(spec.default).trim() === '' ? null : String(spec.default).trim(),
    position,
  });
}

