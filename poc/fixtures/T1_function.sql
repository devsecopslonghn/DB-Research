CREATE OR REPLACE EDITIONABLE FUNCTION "OSS_POC_WRITER"."OSS_POC_CLOB_LEN" (
  P_INPUT IN CLOB
) RETURN NUMBER AUTHID DEFINER AS
BEGIN
  IF P_INPUT IS NULL THEN
    RETURN 0;
  END IF;
  RETURN DBMS_LOB.GETLENGTH(P_INPUT);
END;
/
GRANT EXECUTE ON "OSS_POC_WRITER"."OSS_POC_CLOB_LEN" TO "OSS_POC_OBSERVER";
